"""
castle/ui/cluster_tree.py
Tree view rendering for cluster hierarchy.

Cluster names use '_' as the hierarchy delimiter, generated by
auto_generate_cluster_name() in castle/core/cluster.py:
    init → init_a0, init_a1
    init_a0 → init_a0_b0, init_a0_b1
    init_a0_b0 → init_a0_b0_c0, ...

Parent nodes (e.g. 'init_a0') are NOT stored in cluster_meta once they
have been split — they exist only as name prefixes of their children.
This module synthesises them for display and computes cumulative counts.
"""

from collections import Counter
from typing import Dict, Optional


def _infer_all_nodes(real_names: set) -> set:
    """Expand a set of real cluster names to include all ancestor prefixes.

    A prefix is a parent node if at least one real cluster name starts
    with ``prefix + '_'``.  This covers arbitrary nesting depth without
    assuming a fixed separator letter pattern.

    Args:
        real_names: set of cluster name strings present in cluster_meta.

    Returns:
        Extended set containing real names + all synthetic parent prefixes.
    """
    parents: set = set()
    for name in real_names:
        parts = name.split('_')
        for i in range(1, len(parts)):
            prefix = '_'.join(parts[:i])
            # Only a valid parent if some real cluster lives under it
            if any(n.startswith(prefix + '_') for n in real_names):
                parents.add(prefix)
    return real_names | parents


def _immediate_parent(name: str, all_nodes: set) -> Optional[str]:
    """Return the longest strict prefix of ``name`` that is in ``all_nodes``."""
    parts = name.split('_')
    for i in range(len(parts) - 1, 0, -1):
        prefix = '_'.join(parts[:i])
        if prefix in all_nodes:
            return prefix
    return None


def _build_tree(cluster_meta: dict, cluster_array) -> Dict[str, dict]:
    """Build a complete tree dict including synthetic parent nodes.

    Args:
        cluster_meta: {id: {name, color, ...}}
        cluster_array: numpy array of per-frame cluster assignments.

    Returns:
        dict {name: {depth, cumulative, is_real, meta, cid}}
        Sorted by name (preserves hierarchical ordering).
    """
    direct = Counter(cluster_array.tolist())
    name_to_cid = {meta['name']: cid for cid, meta in cluster_meta.items()}
    real_names = set(name_to_cid.keys())

    all_nodes = _infer_all_nodes(real_names)

    # Cumulative count: start with direct counts for real nodes
    cum: Dict[str, int] = {
        n: (direct.get(name_to_cid[n], 0) if n in real_names else 0)
        for n in all_nodes
    }

    # Depth via parent chain
    parent_map = {n: _immediate_parent(n, all_nodes) for n in all_nodes}

    def depth_of(name: str) -> int:
        d, n = 0, name
        while parent_map.get(n) is not None:
            d += 1
            n = parent_map[n]
        return d

    depth_map = {n: depth_of(n) for n in all_nodes}

    # Bottom-up accumulation: deepest nodes first
    for name in sorted(all_nodes, key=lambda n: -depth_map[n]):
        parent = parent_map.get(name)
        if parent is not None:
            cum[parent] = cum.get(parent, 0) + cum.get(name, 0)

    result = {}
    for name in sorted(all_nodes):
        cid = name_to_cid.get(name)
        meta = cluster_meta.get(cid) if cid is not None else None
        # A node is a "container" if it has children in all_nodes
        is_container = any(
            parent_map.get(other) == name for other in all_nodes if other != name
        )
        result[name] = {
            'depth': depth_map[name],
            'cumulative': cum.get(name, 0),
            'is_real': name in real_names,
            'is_container': is_container,
            'meta': meta,
            'cid': cid,
        }
    return result


def build_cluster_tree_markdown(cluster_meta, cluster_array):
    """Build a markdown tree from cluster metadata.

    Parent nodes are synthesised from name prefixes and shown with their
    cumulative (subtree) frame count.

    Args:
        cluster_meta: dict {id: {name, color}}
        cluster_array: numpy array of cluster assignments

    Returns:
        Markdown string with tree visualization
    """
    tree = _build_tree(cluster_meta, cluster_array)
    lines = []
    for name, info in tree.items():
        if info['cumulative'] == 0:
            continue
        depth = info['depth']
        indent = '    ' * depth
        prefix = '├── ' if depth > 0 else ''
        line = f"{indent}{prefix}🔸 **{name}** ({info['cumulative']} bins)"
        lines.append(line)

    if not lines:
        return "*No clusters yet*"
    return "### 📊 Cluster Tree\n\n" + "\n\n".join(lines)


