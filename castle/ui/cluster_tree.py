def build_cluster_tree_html(cluster_meta: dict, cluster_array) -> str:
    """Build an HTML visual tree of the cluster hierarchy (display-only).

    Uses CSS ``padding-left`` for indentation — reliable across all browsers
    and unaffected by HTML whitespace collapsing.

    Args:
        cluster_meta: dict {id: {name, color, ...}}
        cluster_array: numpy array of per-frame cluster assignments.

    Returns:
        HTML string for ``gr.HTML`` component.
    """
    tree = _build_tree(cluster_meta, cluster_array)

    rows = []
    for name, info in tree.items():
        if info['cumulative'] == 0:
            continue
        depth = info['depth']
        indent_px = 8 + depth * 20

        if info['is_container']:
            icon = '📂'
        else:
            color = (info['meta'] or {}).get('color', 'grey')
            icon = '🟢' if color != 'grey' else '📁'

        safe_name = name.replace("'", "\\'")
        rows.append(
            f'<div class="cct-node" style="padding-left:{indent_px}px"'
            f' onclick="castleTreeClick(this,\'{safe_name}\')"'
            f' data-name="{name}">'
            f'<span class="cct-icon">{icon}</span>'
            f'<span class="cct-name">{name}</span>'
            f'<span class="cct-count">{info["cumulative"]}</span>'
            f'</div>'
        )

    if not rows:
        return (
            f'{_TREE_CSS}'
            '<div class="castle-cluster-tree">'
            '<span style="color:#888;font-style:italic;padding:6px;display:block">'
            'No clusters yet — run DBSCAN to create clusters.'
            '</span></div>'
        )

    return (
        f'{_TREE_CSS}'
        '<div class="castle-cluster-tree">\n'
        + '\n'.join(rows)
        + '\n</div>'
    )


def build_cluster_tree_choices(cluster_meta, cluster_array):
    """Build tree-formatted choices for gr.Radio.

    Returns list of (display_label, value) where:
    - display_label has indentation + branch chars + frame count
    - value is the cluster name (used for selection)

    Parent/container nodes are included; selecting them will drill into
    the full subtree (handled by latent_explorer.select with prefix matching).

    Args:
        cluster_meta: dict {id: {name, color}}
        cluster_array: numpy array of cluster assignments

    Returns:
        List of (label, value) tuples for gr.Radio choices
    """
    tree = _build_tree(cluster_meta, cluster_array)
    choices = []
    for name, info in tree.items():
        if info['cumulative'] == 0:
            continue
        depth = info['depth']
        # Use non-breaking spaces so HTML does not collapse the indentation.
        # 4 NBSP per depth level gives clear visual separation in gr.Radio.
        nbsp = ' '
        indent = nbsp * 4 * depth
        prefix = f'├──{nbsp}' if depth > 0 else ''

        if info['is_container']:
            icon = '📂'
        else:
            color = (info['meta'] or {}).get('color', 'grey')
            icon = '🟢' if color != 'grey' else '📁'

        display_label = f"{indent}{prefix}{icon}{nbsp}{name} ({info['cumulative']} frames)"
        choices.append((display_label, name))

    return choices
